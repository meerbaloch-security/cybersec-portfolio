"""Analyst-style incident reports (Markdown) and JSON export."""

from __future__ import annotations

from .incidents import Incident

STATUS = {"True positive": "Escalated to Tier 2 / Incident Response", "Benign": "Closed (benign, justified)",
          "Inconclusive": "Open: awaiting information"}


def incident_markdown(inc: Incident) -> str:
    out = [f"# {inc.id}: {inc.title}", "",
           "| | |", "|---|---|",
           f"| **Verdict** | {inc.verdict} |",
           f"| **Confidence** | {inc.confidence} |",
           f"| **Severity** | {inc.severity} (risk {inc.risk}/100) |",
           f"| **Status** | {STATUS[inc.verdict]} |",
           f"| **Window** | {inc.start:%Y-%m-%d %H:%M:%S} – {inc.end:%H:%M:%S} UTC |",
           f"| **Alerts** | {len(inc.alerts)} |",
           f"| **Users** | {', '.join(inc.entities['user']) or '-'} |",
           f"| **Hosts** | {', '.join(inc.entities['host']) or '-'} |",
           f"| **Prepared by** | Tier 1 SOC (draft generated by soc-sim; analyst review required) |",
           "", "## Executive summary", "", inc.summary, ""]
    out += ["## Timeline", "", "| Time (UTC) | Type | Event | Detail |", "|---|---|---|---|"]
    for t in inc.timeline:
        kind = "🚨 alert" if t.kind == "alert" else "context"
        note = f" *(explained: {t.explained})*" if t.explained else ""
        detail = t.detail if len(t.detail) <= 150 else t.detail[:147] + "…"
        out.append(f"| {t.time:%H:%M:%S} | {kind} | {t.title}{f' `{t.technique}`' if t.technique else ''} | "
                   f"{detail.replace('|', '/')}{note} |")
    if inc.techniques:
        out += ["", "## MITRE ATT&CK mapping", "", "| Technique | Name | Observed evidence |", "|---|---|---|"]
        out += [f"| [{t['id']}](https://attack.mitre.org/techniques/{t['id'].replace('.', '/')}/) | {t['name']} | "
                f"{t['evidence']} at {t['time']} |" for t in inc.techniques]
        if inc.tactics:
            out += ["", f"**Progression:** {' → '.join(inc.tactics)}"]
    out += ["", "## Analysis", "", "**Evidence supporting malicious activity**", ""]
    out += [f"- {x}" for x in inc.evidence_for] or ["- None"]
    out += ["", "**Evidence against / benign explanations**", ""]
    out += [f"- {x}" for x in inc.evidence_against] or ["- None"]
    if inc.observations:
        out += ["", "**Enrichment and observations**", ""] + [f"- {x}" for x in inc.observations]
    out += ["", "## Conclusion", "",
            f"**{inc.verdict}**, {inc.confidence.lower()} confidence (evidence score {inc.score}). "
            + {"True positive": "The correlated evidence is consistent with an intrusion and is not explained by any known change or allowlist.",
               "Benign": "Every alert is explained by documented, approved context.",
               "Inconclusive": "The activity is suspicious but the telemetry cannot distinguish an approved action from data theft."}[inc.verdict],
            "", "## Open questions and uncertainties", ""]
    out += [f"- {x}" for x in inc.uncertainties] or ["- None"]
    if inc.iocs:
        out += ["", "## Indicators of compromise", "", "| Type | Value |", "|---|---|"]
        out += [f"| {i['type']} | `{i['value']}` |" for i in inc.iocs]
    out += ["", "## Recommended actions", ""]
    for phase, items in inc.recommendations.items():
        out += [f"**{phase}**", ""] + [f"1. {x}" for x in items] + [""]
    out += ["---", "_Recommendations only: soc-sim never changes accounts or systems._"]
    return "\n".join(out)


def incident_json(inc: Incident) -> dict:
    return {
        "id": inc.id, "title": inc.title, "verdict": inc.verdict, "confidence": inc.confidence,
        "severity": inc.severity, "risk": inc.risk, "score": inc.score, "status": STATUS[inc.verdict],
        "start": inc.start.isoformat(), "end": inc.end.isoformat(), "entities": inc.entities,
        "tactics": inc.tactics, "stage": inc.stage, "techniques": inc.techniques, "summary": inc.summary,
        "evidence_for": inc.evidence_for, "evidence_against": inc.evidence_against,
        "observations": inc.observations, "uncertainties": inc.uncertainties,
        "recommendations": inc.recommendations, "iocs": inc.iocs,
        "alerts": [{"id": a.id, "rule": a.rule_name, "title": a.title, "level": a.level, "time": a.time.isoformat(),
                    "techniques": a.techniques, "explained": inc.explained.get(a.id), "events": len(a.events)}
                   for a in inc.alerts],
        "timeline": [{"time": t.time.strftime("%H:%M:%S"), "kind": t.kind, "title": t.title, "detail": t.detail,
                      "technique": t.technique, "explained": t.explained} for t in inc.timeline],
        "report_markdown": incident_markdown(inc),
    }
